    fn encrypt_strings() -> Vec<Vec<u8>> {
        STRINGS.map(|string| {
            let plaintext = base64_to_bytes(string);
            ctr(&plaintext, &AES_KEY, 0)
        })
        .to_vec()
    }

    #[test]
    fn s03_c19_breaking_fixed_nonce_ctr_with_substitutions() {
        let ciphertexts = encrypt_strings();

        let max_len = ciphertexts.iter().map(Vec::len).max().unwrap_or(0);
        let transposed = (0..max_len)
            .map(|i| {
                ciphertexts
                    .iter()
                    .filter_map(|v| v.get(i).cloned())
                    .collect_vec()
            })
            .collect_vec();

        let keystream = transposed.iter().map(|nth_bytes| {
            let (key, _plaintext, _score) = crack_single_byte_xor(&nth_bytes);
            key
        }).collect_vec();

        for ciphertext in ciphertexts {
            let keystream = keystream[..ciphertext.len()].to_vec();
            let plaintext = xor_slice(&ciphertext, &keystream);
            println!("{}", bytes_to_ascii(&plaintext))
        }
        
        let real_keystream = (0..2).map(|i: u64| {
            Aes128EcbEnc::new_from_slice(&AES_KEY)
                .unwrap()
                .encrypt_padded_vec::<NoPadding>(&&[0_u64.to_le_bytes(), i.to_le_bytes()].concat())
            })
            .concat();

        // little more lenient assertion because of intended manual solution
        assert_eq!(keystream[1..30], real_keystream[1..30]);
    }
